//! Explicit user-owned tmux sessions on the login user's default socket.
//! Never installs software, changes tmux configuration, detaches other clients or kills sessions.
use super::client::{AuthenticatedConnection, SshClient};
use super::exec::{run_captured, sh_c};
use serde::{Deserialize, Serialize};
use std::{collections::HashMap, sync::Arc};
use tokio::sync::Mutex;
use tokio::time::{timeout, Duration};

#[derive(Clone, Debug, Deserialize)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum TmuxChoice {
    Attach {
        id: String,
        created: u64,
        server_pid: u32,
    },
    Create {
        name: String,
    },
}

#[derive(Clone, Debug, Serialize, PartialEq)]
pub struct TmuxSession {
    pub id: String,
    pub name: String,
    pub windows: u32,
    pub attached: u32,
    pub created: u64,
    pub server_pid: u32,
}

#[derive(Debug, Serialize)]
pub struct TmuxListing {
    pub installed: bool,
    pub sessions: Vec<TmuxSession>,
}

struct Prepared {
    host: String,
    port: u16,
    username: String,
    connection: AuthenticatedConnection,
}

/// Short-lived, one-use authenticated connections; no passwords or keys are retained here.
#[derive(Clone, Default)]
pub struct TmuxPickers(Arc<Mutex<HashMap<String, Prepared>>>);

pub async fn disconnect(connection: &AuthenticatedConnection) {
    let _ = connection
        .handle
        .disconnect(russh::Disconnect::ByApplication, "Picker closed", "en")
        .await;
    for handle in &connection.jump_handles {
        let _ = handle
            .disconnect(russh::Disconnect::ByApplication, "Picker closed", "en")
            .await;
    }
}

impl TmuxPickers {
    pub async fn insert(
        &self,
        id: String,
        host: String,
        port: u16,
        username: String,
        connection: AuthenticatedConnection,
    ) -> Result<(), String> {
        // Tokens are fresh UUIDs generated by this client, never an existing terminal id.
        let mut pending = self.0.lock().await;
        if pending.contains_key(&id) {
            drop(pending);
            disconnect(&connection).await;
            return Err("TMUX_PICKER_TOKEN_REUSED".into());
        }
        pending.insert(
            id.clone(),
            Prepared {
                host,
                port,
                username,
                connection,
            },
        );
        drop(pending);
        let registry = self.clone();
        tokio::spawn(async move {
            tokio::time::sleep(Duration::from_secs(300)).await;
            registry.cancel(&id).await;
        });
        Ok(())
    }

    pub async fn take(
        &self,
        id: &str,
        host: &str,
        port: u16,
        username: &str,
    ) -> Result<AuthenticatedConnection, String> {
        let mut pending = self.0.lock().await;
        let entry = pending.get(id).ok_or("TMUX_PICKER_EXPIRED")?;
        if entry.host != host || entry.port != port || entry.username != username {
            return Err("TMUX_PICKER_HOST_CHANGED".into());
        }
        Ok(pending
            .remove(id)
            .expect("entry checked under the same lock")
            .connection)
    }

    pub async fn cancel(&self, id: &str) {
        let entry = self.0.lock().await.remove(id);
        if let Some(entry) = entry {
            disconnect(&entry.connection).await;
        }
    }
}

const SESSION_FORMAT: &str = "#{session_id}\t#{session_name}\t#{session_windows}\t#{session_attached}\t#{session_created}\t#{pid}";

fn list_command() -> String {
    sh_c(&format!("unset TMUX TMUX_PANE; command -v tmux >/dev/null 2>&1 || exit 127; LC_ALL=C tmux list-sessions -F {}", super::exec::shell_quote(SESSION_FORMAT)), &[])
}

pub fn valid_id(id: &str) -> bool {
    id.starts_with('$') && id.len() > 1 && id[1..].bytes().all(|b| b.is_ascii_digit())
}

pub fn validate_name(name: &str) -> Result<(), String> {
    if name.trim().is_empty()
        || name.len() > 128
        || name.starts_with('-')
        || name.chars().any(|c| c.is_control() || c == '.' || c == ':')
    {
        return Err("TMUX_INVALID_NAME".into());
    }
    Ok(())
}

fn parse_listing(out: &str) -> Result<Vec<TmuxSession>, String> {
    out.lines()
        .filter(|line| !line.is_empty())
        .map(|line| {
            let fields: Vec<_> = line.split('\t').collect();
            if fields.len() != 6 || !valid_id(fields[0]) || fields[1].chars().any(char::is_control)
            {
                return Err("TMUX_INVALID_LIST_RESPONSE".into());
            }
            Ok(TmuxSession {
                id: fields[0].into(),
                name: fields[1].into(),
                windows: fields[2]
                    .parse()
                    .map_err(|_| "TMUX_INVALID_LIST_RESPONSE")?,
                created: fields[4]
                    .parse()
                    .map_err(|_| "TMUX_INVALID_LIST_RESPONSE")?,
                server_pid: fields[5]
                    .parse()
                    .map_err(|_| "TMUX_INVALID_LIST_RESPONSE")?,
                attached: fields[3]
                    .parse()
                    .map_err(|_| "TMUX_INVALID_LIST_RESPONSE")?,
            })
        })
        .collect()
}

async fn run(
    handle: &russh::client::Handle<SshClient>,
    command: &str,
) -> Result<super::exec::Captured, String> {
    timeout(Duration::from_secs(15), run_captured(handle, command))
        .await
        .map_err(|_| "TMUX_COMMAND_TIMEOUT".to_string())?
}

pub async fn list(connection: &AuthenticatedConnection) -> Result<TmuxListing, String> {
    if connection.remote_is_windows {
        return Ok(TmuxListing {
            installed: false,
            sessions: vec![],
        });
    }
    let result = run(&connection.handle, &list_command()).await?;
    listing_result(result)
}

fn listing_result(result: super::exec::Captured) -> Result<TmuxListing, String> {
    match result.code {
        Some(0) => Ok(TmuxListing {
            installed: true,
            sessions: parse_listing(&result.stdout_text())?,
        }),
        Some(127) => Ok(TmuxListing {
            installed: false,
            sessions: vec![],
        }),
        Some(1)
            if result.stderr.contains("no server running")
                || result.stderr.contains("no sessions")
                || (result.stderr.contains("error connecting to")
                    && result.stderr.contains("No such file or directory")) =>
        {
            Ok(TmuxListing {
                installed: true,
                sessions: vec![],
            })
        }
        _ => Err(format!("TMUX_LIST_FAILED: {}", result.stderr.trim())),
    }
}

fn tmux_name_argument(name: &str) -> String {
    // -s is format-expanded, and tmux's argv parser treats a final ';' as a command separator.
    // Shell quoting alone protects neither layer; preserve names as data in both parsers.
    let mut argument = name.replace('#', "##");
    if argument.ends_with(';') {
        argument.insert(argument.len() - 1, '\\');
    }
    argument
}

fn choice_command(choice: &TmuxChoice) -> Result<String, String> {
    let format = super::exec::shell_quote(SESSION_FORMAT);
    let (command, argument) = match choice {
        TmuxChoice::Attach { id, .. } => {
            if !valid_id(id) {
                return Err("TMUX_INVALID_SESSION_ID".into());
            }
            (
                format!("tmux display-message -p -t \"$1\" {format}"),
                id.clone(),
            )
        }
        TmuxChoice::Create { name } => {
            validate_name(name)?;
            // tmux performs the unique-name check atomically. Never use new-session -A.
            (
                format!("tmux new-session -d -P -F {format} -s \"$1\""),
                tmux_name_argument(name),
            )
        }
    };
    Ok(sh_c(
        &format!("unset TMUX TMUX_PANE; {command}"),
        &[argument.as_str()],
    ))
}

pub async fn resolve_choice(
    handle: &russh::client::Handle<SshClient>,
    choice: TmuxChoice,
) -> Result<TmuxSession, String> {
    let result = run(handle, &choice_command(&choice)?).await?;
    if result.code != Some(0) {
        return Err(format!("TMUX_CHOICE_FAILED: {}", result.stderr.trim()));
    }
    let mut sessions = parse_listing(&result.stdout_text())?;
    if sessions.len() != 1 {
        return Err("TMUX_INVALID_SESSION_RESPONSE".into());
    }
    let session = sessions.remove(0);
    if let TmuxChoice::Attach {
        id,
        created,
        server_pid,
    } = choice
    {
        if session.id != id || session.created != created || session.server_pid != server_pid {
            return Err("TMUX_SESSION_CHANGED_REFRESH_LIST".into());
        }
    }
    Ok(session)
}

pub fn attach_command(id: &str) -> Result<String, String> {
    if !valid_id(id) {
        return Err("TMUX_INVALID_SESSION_ID".into());
    }
    // No -d: leave already attached clients alone. Default socket, not Voltius's private one.
    Ok(sh_c(
        "unset TMUX TMUX_PANE; exec tmux attach-session -t \"$1\"",
        &[id],
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_sessions_preserves_names_and_reports_attached_clients() {
        assert_eq!(
            parse_listing("$0\t工作 shell\t2\t1\t123\t42\n$12\ta'b;$x\t1\t0\t124\t42\n").unwrap(),
            vec![
                TmuxSession {
                    id: "$0".into(),
                    name: "工作 shell".into(),
                    windows: 2,
                    attached: 1,
                    created: 123,
                    server_pid: 42,
                },
                TmuxSession {
                    id: "$12".into(),
                    name: "a'b;$x".into(),
                    windows: 1,
                    attached: 0,
                    created: 124,
                    server_pid: 42,
                },
            ]
        );
        assert!(parse_listing("").unwrap().is_empty());
        assert!(parse_listing("banner").is_err());
        assert!(parse_listing("$0\tx\tNaN\t0").is_err());
    }

    #[test]
    fn names_are_quoted_as_data_and_never_create_or_attach_by_accident() {
        assert_eq!(
            tmux_name_argument("工作 #S #{pid} #(printf BAD);"),
            "工作 ##S ##{pid} ##(printf BAD)\\;"
        );
        assert_eq!(tmux_name_argument("backslash\\;"), "backslash\\\\;");
        let name = "work ' $(touch /tmp/SHOULD_NOT_EXIST); 测试";
        let cmd = choice_command(&TmuxChoice::Create { name: name.into() }).unwrap();
        assert!(cmd.contains("new-session -d -P"));
        assert!(!cmd.contains("new-session -A"));
        assert!(!cmd.contains("attach-session"));
        #[cfg(unix)]
        {
            // Execute only a local echo replacement, never a real host/tmux session.
            let echo = sh_c("printf '%s' \"$1\"", &[name]);
            let out = std::process::Command::new("sh")
                .args(["-c", &echo])
                .output()
                .unwrap();
            assert_eq!(String::from_utf8(out.stdout).unwrap(), name);
        }
    }

    #[test]
    fn invalid_names_and_non_ids_fail_before_any_command() {
        for name in ["", " ", "a:b", "a.b", "a\nb", "-bad"] {
            assert!(validate_name(name).is_err());
        }
        for id in ["", "work", "$", "$1;kill-server", "=work", "$-1"] {
            assert!(attach_command(id).is_err());
        }
        let attach = attach_command("$42").unwrap();
        assert!(attach.contains("attach-session"));
        assert!(!attach.contains(" -d"));
        assert!(!attach.contains("kill-session"));
    }
    #[test]
    fn list_distinguishes_missing_empty_permission_failure_and_missing_exit_status() {
        let captured = |code, stderr: &str| super::super::exec::Captured {
            stdout: vec![],
            stderr: stderr.into(),
            code,
        };
        assert!(!listing_result(captured(Some(127), "")).unwrap().installed);
        for stderr in [
            "no server running on /tmp/test",
            "no sessions",
            "error connecting to /tmp/test (No such file or directory)",
        ] {
            let result = listing_result(captured(Some(1), stderr)).unwrap();
            assert!(result.installed && result.sessions.is_empty());
        }
        assert!(listing_result(captured(Some(1), "permission denied")).is_err());
        assert!(listing_result(captured(None, "")).is_err());
    }

    #[cfg(unix)]
    #[test]
    fn real_tmux_creation_is_unique_and_default_socket_commands_preserve_names() {
        use std::os::unix::fs::PermissionsExt;
        let binary = std::env::var("VOLTIUS_TEST_TMUX").unwrap_or_else(|_| "/usr/bin/tmux".into());
        assert!(
            std::path::Path::new(&binary).exists(),
            "Install tmux in the isolated test runner"
        );
        let directory = tempfile::Builder::new()
            .prefix("voltius-tmux-")
            .tempdir()
            .unwrap();
        let socket = directory.path().join("tmux.sock");
        let launcher = directory.path().join("tmux");
        std::fs::write(
            &launcher,
            format!(
                "#!/bin/sh\nexec {} -S {} -f /dev/null \"$@\"\n",
                super::super::exec::shell_quote(&binary),
                super::super::exec::shell_quote(socket.to_str().unwrap())
            ),
        )
        .unwrap();
        std::fs::set_permissions(&launcher, std::fs::Permissions::from_mode(0o700)).unwrap();
        struct Stop<'a>(&'a std::path::Path);
        impl Drop for Stop<'_> {
            fn drop(&mut self) {
                let _ = std::process::Command::new(self.0)
                    .arg("kill-server")
                    .output();
            }
        }
        let _stop = Stop(&launcher);
        // Our tmux wrapper wins resolution, while sh_c and the login shell still need sh/tools.
        let path = std::env::join_paths(std::iter::once(directory.path().to_path_buf()).chain(
            std::env::split_paths(&std::env::var_os("PATH").unwrap_or_default()),
        ))
        .unwrap();
        let run = |command: &str| {
            std::process::Command::new("/bin/sh")
                .args(["-c", command])
                .env("PATH", &path)
                .env_remove("TMUX")
                .env_remove("TMUX_PANE")
                .output()
                .unwrap()
        };
        let marker = directory.path().join("name-evaluated");
        let name = format!(
            "工作 #{{session_name}} #(touch {}) ' $(printf BAD);",
            marker.display()
        );
        let create = choice_command(&TmuxChoice::Create { name: name.clone() }).unwrap();
        let first = run(&create);
        assert!(
            first.status.success(),
            "{}",
            String::from_utf8_lossy(&first.stderr)
        );
        let created = parse_listing(std::str::from_utf8(&first.stdout).unwrap())
            .unwrap()
            .remove(0);
        assert_eq!(created.name, name);
        assert!(
            !marker.exists(),
            "a name must never execute a tmux format job"
        );
        let duplicate = run(&create);
        assert!(
            !duplicate.status.success(),
            "duplicate creation must fail, never attach"
        );
        assert!(String::from_utf8_lossy(&duplicate.stderr).contains("duplicate session"));
        let list = run(&list_command());
        assert!(list.status.success());
        let sessions = parse_listing(std::str::from_utf8(&list.stdout).unwrap()).unwrap();
        assert_eq!(sessions.len(), 1);
        assert_eq!(sessions[0].id, created.id);
        assert_eq!(sessions[0].name, name);
        let check = run(&choice_command(&TmuxChoice::Attach {
            id: created.id.clone(),
            created: created.created,
            server_pid: created.server_pid,
        })
        .unwrap());
        assert!(check.status.success());
        assert_eq!(
            parse_listing(std::str::from_utf8(&check.stdout).unwrap()).unwrap()[0].name,
            name
        );
        assert!(!marker.exists());
    }
}
